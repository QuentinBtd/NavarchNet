#[cfg(test)]
mod tests {
    use super::*;
    use navarchnet::aws::{
        saved_observation::SavedObservation,
        source_handoff_cidr_coverage::SourceHandoffCidrCoverage,
    };

    #[test]
    fn documented_declarations_preserve_comments_without_trailing_whitespace() {
        let config = Config::default();
        for text in [
            declaration::<SavedObservation>(&config),
            declaration::<CutOrigin>(&config),
        ] {
            assert!(text.lines().all(|line| line == line.trim_end()));
            assert!(text.contains("/**"));
        }
    }

    #[test]
    fn composed_saved_success_contract_names_concrete_arguments_and_json_number_generation() {
        let config = Config::default();
        assert_eq!(
            <SourceHandoffCidrCoverage as TS>::name(&config),
            "SourceHandoffCidrEnvelope<SourceHandoffCidrQuery, SavedObservation, SavedObservation, Array<CutOrigin>, Array<SourceHandoffDecisionInterval>>"
        );
        let envelope = <SourceHandoffCidrCoverage as TS>::decl(&config);
        assert!(envelope.contains("SourceHandoffCidrEnvelope<Q, S, N, O, C>"));
        assert!(envelope.contains("query: Q"));
        assert!(envelope.contains("segments: C"));
        let saved = <SavedObservation as TS>::decl(&config);
        assert!(saved.contains("generation: number"));
        assert!(!saved.contains("bigint"));
        assert!(saved.contains("topology: AwsTopology"));
    }
}
