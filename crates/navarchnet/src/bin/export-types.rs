use ts_rs::{Config, TS};
fn declaration<T: TS>(config: &Config) -> String {
    // ts-rs inserts spaces before documentation newlines; keep generated diffs whitespace-clean.
    T::decl(config)
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n")
}
